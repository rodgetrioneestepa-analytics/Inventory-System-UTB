import bcrypt from 'bcryptjs';
import { mkdtempSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { Store, id, now } from '../backend/src/db.js';
import { createApp } from '../backend/src/app.js';
const dir = mkdtempSync(join(tmpdir(), 'utb-browser-'));
const s = new Store(join(dir, 'browser.sqlite'));
if (!process.env.UTB_E2E_PASSWORD)
  throw new Error('Test password must be generated by the test runner');
for (const role of ['admin', 'staff']) {
  const uid = id();
  await s.run(
    'INSERT INTO users VALUES (?,?,?,?,?,?,?)',
    uid,
    role + '@test.local',
    'TEST ONLY ' + role,
    bcrypt.hashSync(process.env.UTB_E2E_PASSWORD, 4),
    role,
    1,
    now(),
  );
}
createApp(s, { origin: 'http://127.0.0.1:3012', log: false }).listen(3012, '127.0.0.1');
